def get_flat(d, prefix=''):
    flat = {}
    for k, v in d.items():
        p = f"{prefix}.{k}" if prefix else k
        if isinstance(v, dict):
            flat.update(get_flat(v, p))
        else:
            flat[p] = v
    return flat
